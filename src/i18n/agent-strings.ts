const translations: Record<InterfaceLanguage, AgentStrings> = { en, uk, ru, de };

export function createAgentTranslator(language: InterfaceLanguage) {
  return (key: AgentStringKey, params?: Record<string, string | number>) =>
    tAgent(language, key, params);
}

export function tAgent(
  language: InterfaceLanguage,
  key: AgentStringKey,
  params?: Record<string, string | number>
): string {
  let value = translations[language][key] ?? en[key];
  if (params) {
    for (const [name, replacement] of Object.entries(params)) {
      value = value.replaceAll(`{${name}}`, String(replacement));
    }
  }
  return value;
}
