const translations: Record<InterfaceLanguage, DecisionsLiveCheckStrings> = { en, de, uk, ru };

export function createDecisionsLiveCheckTranslator(language: InterfaceLanguage) {
  return (key: DecisionsLiveCheckStringKey, params?: Record<string, string | number>) => {
    let value = translations[language][key] ?? en[key];
    if (params) {
      for (const [name, replacement] of Object.entries(params)) {
        value = value.replaceAll(`{${name}}`, String(replacement));
      }
    }
    return value;
  };
}
