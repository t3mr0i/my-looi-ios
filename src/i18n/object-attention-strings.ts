const dictionaries: Record<InterfaceLanguage, ObjectAttentionStrings> = { en, de, uk, ru };

export function createObjectAttentionTranslator(language: InterfaceLanguage) {
  const dictionary = dictionaries[language];
  return (key: ObjectAttentionStringKey, values?: Record<string, string>) => {
    const template = dictionary[key];
    return Object.entries(values ?? {}).reduce((text, [name, value]) => text.replaceAll(`{${name}}`, value), template);
  };
}
