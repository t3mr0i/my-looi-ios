const translations: Record<InterfaceLanguage, RobotAppsStrings> = { en, uk, ru, de };

export function createRobotAppsTranslator(language: InterfaceLanguage) {
  const strings = translations[language] ?? en;
  return (key: RobotAppsStringKey, vars: Record<string, string | number> = {}): string =>
    strings[key].replace(/\{(\w+)\}/g, (_match, name: string) => String(vars[name] ?? ""));
}

