const translations: Record<InterfaceLanguage, BehaviorRehearsalStrings> = { en, uk, ru, de };

export function createBehaviorRehearsalTranslator(language: InterfaceLanguage) {
  return (key: BehaviorRehearsalStringKey, params?: Record<string, string | number>) => {
    let value = translations[language][key] ?? en[key];
    if (params) {
      for (const [name, replacement] of Object.entries(params)) {
        value = value.replaceAll(`{${name}}`, String(replacement));
      }
    }
    return value;
  };
}
