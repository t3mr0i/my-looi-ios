// Ukrainian and Russian fall back to English for now.
const translations: Partial<Record<InterfaceLanguage, Partial<DeviceCheckStrings>>> = { en, de };

export function createDeviceCheckTranslator(language: InterfaceLanguage) {
  return (key: DeviceCheckStringKey, params?: Record<string, string | number>) => {
    let value = translations[language]?.[key] ?? en[key];
    if (params) {
      for (const [name, replacement] of Object.entries(params)) {
        value = value.replaceAll(`{${name}}`, String(replacement));
      }
    }
    return value;
  };
}
