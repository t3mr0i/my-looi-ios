const translations: Record<InterfaceLanguage, RobotDebugStrings> = { en, uk, ru, de };

export function createRobotDebugTranslator(language: InterfaceLanguage) {
  return (key: RobotDebugStringKey, params?: Record<string, string | number>) => {
    let value = translations[language][key] ?? en[key];
    if (params) {
      for (const [name, replacement] of Object.entries(params)) {
        value = value.replaceAll(`{${name}}`, String(replacement));
      }
    }
    return value;
  };
}
